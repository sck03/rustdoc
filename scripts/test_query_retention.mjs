import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { setTimeout as delay } from "node:timers/promises";
import { largeDocumentQueryOptions } from "../apps/export-doc-web/src/api/queryRetention.ts";
const require = createRequire(new URL("../apps/export-doc-web/package.json", import.meta.url));
const { QueryClient, QueryObserver } = require("@tanstack/react-query");
const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
const key = ["large-document", 1];
const observer = new QueryObserver(client, { ...largeDocumentQueryOptions, queryKey: key, queryFn: async () => ({ text: "x".repeat(4 * 1024 * 1024) }) });
let unsubscribe = observer.subscribe(() => {});
await observer.refetch();
const draft = client.getQueryData(key);
await delay(10);
assert.equal(client.getQueryData(key), draft, "An observed editor retains its document.");
unsubscribe();
unsubscribe = observer.subscribe(() => {});
assert.equal(client.getQueryData(key), draft, "A synchronous React remount retains the snapshot.");
unsubscribe();
await delay(10);
assert.equal(client.getQueryCache().find({ queryKey: key }), undefined, "Inactive large snapshots are collected.");
assert.equal(draft.text.length, 4 * 1024 * 1024, "The editor-owned draft remains intact.");
client.clear();
console.log("Large document query retention passed.");
