//! Emit a small session client and lazy business domains from the same operations.
use super::{Operation, quoted, typescript::identifier};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

pub(super) fn domain(op: &Operation<'_>) -> String {
    let parts: Vec<_> = op.path.trim_matches('/').split('/').collect();
    if parts.first() != Some(&"api")
        || matches!(parts.get(1), Some(&"auth" | &"license" | &"bootstrap"))
    {
        return "session".into();
    }
    // These are generated transport groups, not authorization rules.
    let group = match parts.get(1).copied().unwrap_or("session") {
        "office" => match parts.get(2).copied().unwrap_or("office") {
            "requests" | "approvals" | "approval-settings" | "handling" | "workflows" => "workflow",
            "people" | "directory" => "personnel",
            "notifications" | "announcements" => "communication",
            _ => "office",
        },
        group => group,
    };
    identifier(group, true)
}

pub(super) fn assemble(
    models: String,
    domains: BTreeMap<String, String>,
    assignments: BTreeMap<String, String>,
) -> (String, BTreeMap<String, String>) {
    const HEADER: &str =
        "// <auto-generated />\n// Generated by export-doc-contracts. Do not edit by hand.\n\n";
    let names: BTreeSet<_> = models
        .lines()
        .filter_map(|line| {
            line.strip_prefix("export interface ")
                .or_else(|| line.strip_prefix("export type "))
                .and_then(|line| line.split_whitespace().next())
        })
        .collect();
    let mut files = BTreeMap::new();
    files.insert("models.ts".into(), format!("{}\n", models.trim_end()));
    let runtime = include_str!("api-client-runtime.ts.txt").replace("\r\n", "\n")
        .replace("export function createExportDocManagerApiClient(options: ApiClientOptions): ExportDocManagerApiClient {\n  return new ExportDocManagerApiClient(options);\n}\n\n", "")
        .replace("export class ExportDocManagerApiClient", "export class ApiTransport")
        .replace("/* GENERATED_METHODS */\n", "")
        .replace("  private async request<T>", "  public async request<T>")
        .replace("function encodePath(", "export function encodePath(")
        .replace("function mergeHeaders(", "export function mergeHeaders(")
        .replace("function throwIfAborted(", "export function throwIfAborted(")
        .replace("async function awaitWithSignal<T>", "export async function awaitWithSignal<T>");
    files.insert("transport.ts".into(), format!("{HEADER}{runtime}"));
    let mut client = format!(
        "{HEADER}export * from './models.ts';\nexport {{ ApiError, type ApiClientOptions, type ApiRequestInit, type AccessTokenProvider }} from './transport.ts';\nimport {{ ApiTransport, awaitWithSignal, throwIfAborted, type ApiClientOptions }} from './transport.ts';\nimport createSessionApi from './domains/session.ts';\n"
    );
    let mut inherited = vec![];
    for (domain, methods) in &domains {
        let alias = format!("{}Api", identifier(domain, false));
        writeln!(
            client,
            "import type {{ Api as {alias} }} from './domains/{domain}.ts';"
        )
        .unwrap();
        inherited.push(alias);
        let used: BTreeSet<_> = methods
            .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
            .filter(|name| names.contains(name))
            .collect();
        let mut imports = vec!["type ApiTransport", "type ApiRequestInit"];
        if methods.contains("encodePath(") {
            imports.push("encodePath");
        }
        if methods.contains("mergeHeaders(") {
            imports.push("mergeHeaders");
        }
        let mut source = format!(
            "{HEADER}import {{ {} }} from '../transport.ts';\n",
            imports.join(", ")
        );
        if !used.is_empty() {
            writeln!(
                source,
                "import type {{ {} }} from '../models.ts';",
                used.into_iter().collect::<Vec<_>>().join(", ")
            )
            .unwrap();
        }
        writeln!(source, "\nexport default function createApi(transport: ApiTransport) {{\n  return {{\n{methods}  }};\n}}\nexport type Api = ReturnType<typeof createApi>;").unwrap();
        files.insert(format!("domains/{domain}.ts"), source);
    }
    writeln!(
        client,
        "\nexport interface ExportDocManagerApiClient extends {} {{}}\n",
        inherited.join(", ")
    )
    .unwrap();
    client.push_str("const loaders = {\n");
    for domain in domains.keys().filter(|domain| *domain != "session") {
        writeln!(client, "  {domain}: () => import('./domains/{domain}.ts'),").unwrap();
    }
    client.push_str("} as const;\ntype Domain = keyof typeof loaders;\nconst operationDomains: Record<string, Domain> = {\n");
    for (method, domain) in &assignments {
        if domain != "session" {
            writeln!(client, "  {method}: {},", quoted(domain)).unwrap();
        }
    }
    client.push_str("};\n");
    client.push_str(include_str!("api-client-lazy.ts.txt"));
    (client, files)
}
