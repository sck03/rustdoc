import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspace = path.join(repoRoot, ".codex-runtime", "authentication-failure-event-tests");
const entry = path.join(workspace, "entry.ts");
const bundle = path.join(workspace, "bundle.mjs");
fs.rmSync(workspace, { recursive: true, force: true });
fs.mkdirSync(workspace, { recursive: true });

const modelPath = path.join(repoRoot, "apps", "export-doc-web", "src", "api", "authenticationFailureEvents.ts").replaceAll("\\", "/");
const apiPath = path.join(repoRoot, "apps", "export-doc-web", "src", "api", "index.ts").replaceAll("\\", "/");
const sessionClientPath=path.join(repoRoot,"apps","export-doc-web","src","app","sessionApiClient.ts").replaceAll("\\","/");
fs.writeFileSync(entry, `import * as model from ${JSON.stringify(modelPath)}; import { ApiError } from ${JSON.stringify(apiPath)}; import { createSessionApiClient, revokeSession, sessionAuthorizationKey } from ${JSON.stringify(sessionClientPath)}; globalThis.__model = { ...model, ApiError, createSessionApiClient, revokeSession, sessionAuthorizationKey };`, "utf8");
const esbuild = require(path.join(repoRoot, "apps", "export-doc-web", "node_modules", "esbuild"));
await esbuild.build({ entryPoints: [entry], outfile: bundle, bundle: true, format: "esm", platform: "node", logLevel: "silent" });
await import(pathToFileURL(bundle).href);

const { ApiError, notifyAuthenticationFailure, subscribeToAuthenticationFailure } = globalThis.__model;
const assert = (condition, message) => { if (!condition) throw new Error(message); };
let notifications = 0;
const unsubscribe = subscribeToAuthenticationFailure(() => { notifications += 1; });

assert(!notifyAuthenticationFailure(new ApiError(403, "Forbidden", "")), "403 must remain a permission error");
assert(!notifyAuthenticationFailure(new ApiError(409, "Conflict", "")), "409 must remain a business conflict");
assert(notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "401 should schedule logout");
assert(!notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "simultaneous 401 responses should be coalesced");
await new Promise((resolve) => setTimeout(resolve, 0));
assert(notifications === 1, "coalesced 401 responses should notify once");
unsubscribe();
assert(notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "401 should still be recognized without listeners");
await new Promise((resolve) => setTimeout(resolve, 0));
assert(notifications === 1, "unsubscribed listener must not run");
const {createSessionApiClient}=globalThis.__model;
let current=true, failures=0, resolveResponse, signalStarted;
let requestStarted=new Promise(resolve=>{signalStarted=resolve;});
const releaseListener=subscribeToAuthenticationFailure(()=>{failures+=1;});
const unauthorized=()=>new Response(JSON.stringify({message:"会话已过期"}),{status:401,headers:{"content-type":"application/json"}});
const delayedFetch=()=>new Promise(resolve=>{resolveResponse=resolve;signalStarted();});
const oldClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"old-session",fetch:delayedFetch},()=>current);
const staleRequest=oldClient.getCurrentUser().catch(()=>{});
await requestStarted;
current=false;resolveResponse(unauthorized());await staleRequest;await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===0,"a late 401 from the previous session must not end its replacement");
const validClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"current-session",fetch:async()=>unauthorized()},()=>true);
await validClient.getCurrentUser().catch(()=>{});await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===1,"an authentication failure from the active session must be reported");
const abort=new AbortController();
requestStarted=new Promise(resolve=>{signalStarted=resolve;});
const abortedClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"current-session",fetch:delayedFetch},()=>true);
const abortedRequest=abortedClient.getCurrentUser({signal:abort.signal}).catch(()=>{});
await requestStarted;
abort.abort();resolveResponse(unauthorized());await abortedRequest;await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===1,"an aborted request must not invalidate an active session");
let token = "before-renewal", sentAuthorization;
requestStarted = new Promise(resolve => { signalStarted = resolve; });
const renewingClient = createSessionApiClient({ baseUrl: "http://localhost", accessToken: () => token,
  fetch: (input, init) => { sentAuthorization = new Headers(init.headers).get("authorization"); return delayedFetch(); }
}, requestToken => requestToken === token);
const renewingRequest = renewingClient.getCurrentUser().catch(() => {});
await requestStarted;
assert(sentAuthorization === "Bearer before-renewal", "request must bind the token actually sent");
token = "after-renewal";
resolveResponse(unauthorized());
await renewingRequest; await new Promise(resolve => setTimeout(resolve, 0));
assert(failures === 1, "a delayed 401 must not expire a renewed token on the same client");
requestStarted = new Promise(resolve => { signalStarted = resolve; });
const nextRequest = renewingClient.getCurrentUser().catch(() => {});
await requestStarted;
assert(sentAuthorization === "Bearer after-renewal", "the stable client must send the renewed token");
resolveResponse(unauthorized()); await nextRequest; await new Promise(resolve => setTimeout(resolve, 0));
assert(failures === 2, "a 401 for the renewed token still expires the current session");
let allowed = true;
requestStarted = new Promise(resolve => { signalStarted = resolve; });
const scopedClient = createSessionApiClient({baseUrl:"http://localhost",accessToken:"same-account",fetch:delayedFetch},()=>true,()=>allowed);
let staleApplied = false;
const pendingSuccess = scopedClient.getCurrentUser().then(()=>{staleApplied=true;},error=>assert(error.name==="AbortError","scope revocation must cancel the result"));
await requestStarted;
allowed = false;
resolveResponse(new Response(JSON.stringify({id:1,capabilities:{canManageUsers:true}}),{headers:{"content-type":"application/json"}}));
await pendingSuccess;
assert(!staleApplied,"a successful old-permission response must not refill the cleared workspace");
const { sessionAuthorizationKey } = globalThis.__model;
const scopeSession = {apiBaseUrl:"http://localhost",accessToken:"one",user:{id:1,contextId:"unit-A",departmentId:"D",capabilities:{canManageUsers:true}}};
const key = sessionAuthorizationKey(scopeSession);
assert(key === sessionAuthorizationKey({...scopeSession,accessToken:"renewed",user:{...scopeSession.user,businessDate:"2026-11-22"}}),"renewal and date rollover preserve command scope");
assert(key !== sessionAuthorizationKey({...scopeSession,user:{...scopeSession.user,capabilities:{canManageUsers:false}}}),"same-account permission changes replace command scope");
assert(key !== sessionAuthorizationKey({...scopeSession,user:{...scopeSession.user,departmentId:"NEW"}}),"department changes replace data scope");
assert(key !== sessionAuthorizationKey({...scopeSession,user:{...scopeSession.user,employee:{id:20,appointmentId:"new-appointment",status:"Active"}}}),"personnel identity changes replace the ownership scope");
allowed = true;
let startBody, finishBody;
const bodyStarted = new Promise(resolve=>{startBody=resolve;});
const bodyClient = createSessionApiClient({baseUrl:"http://localhost",accessToken:"same-account",fetch:async()=>({ok:true,headers:new Headers({"content-type":"application/json"}),text:()=>new Promise(resolve=>{finishBody=resolve;startBody();})})},()=>true,()=>allowed);
const pendingBody = bodyClient.getCurrentUser().then(()=>{throw new Error("obsolete body was accepted");},error=>assert(error.name==="AbortError","scope must be checked after reading response content"));
await bodyStarted; allowed=false; finishBody('{"id":1}'); await pendingBody;
let generation = 0;
requestStarted = new Promise(resolve=>{signalStarted=resolve;});
const beforePause = createSessionApiClient({baseUrl:"http://localhost",accessToken:()=>"renewed-same-account",fetch:delayedFetch},()=>true,()=>generation===0);
const pausedRequest = beforePause.getCurrentUser().then(()=>{throw new Error("a replaced authorization generation was accepted");},error=>assert(error.name==="AbortError","restoring the same identity must not revive old commands"));
await requestStarted; generation += 1;
resolveResponse(new Response('{"id":1}',{headers:{"content-type":"application/json"}}));
await pausedRequest;
releaseListener();
const { revokeSession } = globalThis.__model;
let logoutFetches = 0;
let activeToken = "revoked-session";
let releaseDesktop;
const desktopReady = new Promise(resolve => { releaseDesktop = resolve; });
const logout = revokeSession({ baseUrl: "http://localhost", accessToken: activeToken,
  desktopAccessToken: () => desktopReady,
  fetch: async (url, init) => {
    logoutFetches += 1;
    assert(url.pathname === "/api/auth/logout", "logout must reach the server endpoint");
    assert(new Headers(init.headers).get("authorization") === "Bearer revoked-session", "revocation must retain the submitted session identity");
    return new Response(null, { status: 204 });
  },
});
activeToken = "replacement-session";
releaseDesktop("desktop-token");
await logout;
assert(logoutFetches === 1, "logout must not disappear while resolving desktop credentials");
await revokeSession({ baseUrl: "http://localhost", accessToken: "expired", fetch: async () => unauthorized() });
let failedLogout = false;
try { await revokeSession({ baseUrl: "http://localhost", accessToken: activeToken, fetch: async () => new Response("unavailable", { status: 503 }) }); }
catch (error) { failedLogout = error instanceof ApiError && error.status === 503; }
assert(failedLogout, "failed revocation must be reported so the workspace can keep its session");
fs.rmSync(workspace, { recursive: true, force: true });
process.stdout.write("authentication failure event tests passed\n");
