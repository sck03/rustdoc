import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { captureScreenshot } from './web-runtime-browser-session.mjs';

export async function verifyGridAuthoring({ page, url, read, waitFor, click, key, results, output }) {
  const inspector = '.report-designer-v3-inspector';
  const control = label => `[...document.querySelectorAll('${inspector} label')].find(node=>node.querySelector('span')?.textContent.trim()===${JSON.stringify(label)}).querySelector('input,select,textarea')`;
  const settle = () => read(page, 'new Promise(resolve=>requestAnimationFrame(resolve))');
  const button = async label => { await read(page, `[...document.querySelectorAll('${inspector} button')].find(node=>node.textContent.trim()===${JSON.stringify(label)}).click()`); await settle(); };
  const select = async (label, value) => { await read(page, `(()=>{const node=${control(label)};const setter=Object.getOwnPropertyDescriptor(node instanceof HTMLSelectElement?HTMLSelectElement.prototype:HTMLInputElement.prototype,'value').set;setter.call(node,${JSON.stringify(value)});node.dispatchEvent(new Event('input',{bubbles:true}));node.dispatchEvent(new Event('change',{bubbles:true}));})()`); await settle(); };
  const focus = label => read(page, `(()=>{const node=${control(label)};node.focus();node.select();})()`);
  const fill = async (label, value) => { await focus(label); await page.send('Input.insertText', { text: String(value) }); await key(page, 'Enter'); };
  const block = `window.__designerSchema.layers.flatMap(layer=>layer.elements).find(element=>element.flowKind==='Grid').block`;
  await page.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await page.send('Page.navigate', { url: `${url}?blank=1&payment=1` });
  await waitFor(page, 'document.querySelector("[data-v3-page-canvas]") && window.__designerDraftState');
  await read(page, `document.querySelector('.report-designer-v3-toolbar details').open=true`);
  await click(page, '[aria-label="普通表格"]');
  await select('内容类型', 'CheckboxGroup');
  await select('判断字段', 'Payment.PaymentMethod');
  await waitFor(page, `${block}.rows[0].cells[0].fieldPath==='Payment.PaymentMethod'`);
  const updates = await read(page, 'window.__designerUpdates');
  await focus('勾选项（每行：名称=值）');
  await page.send('Input.insertText', { text: '支票=支票' });
  await key(page, 'Enter');
  assert.equal(await read(page, `${control('勾选项（每行：名称=值）')}.value`), '支票=支票\n', 'Enter must preserve the next checkbox option line');
  await page.send('Input.insertText', { text: '电汇=即期=电汇' });
  assert.equal(await read(page, 'window.__designerUpdates'), updates, 'typing options must not serialize the whole template');
  await key(page, 'Enter', 2);
  await waitFor(page, `${block}.rows[0].cells[0].checkboxOptions.length===2`);
  assert.deepEqual(await read(page, `${block}.rows[0].cells[0].checkboxOptions.map(({label,value})=>({label,value}))`), [{ label: '支票', value: '支票' }, { label: '电汇', value: '即期=电汇' }]);
  assert.equal(await read(page, 'window.__designerUpdates'), updates + 1);
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `${block}.rows[0].cells[0].checkboxOptions.length===0`);
  await click(page, '[aria-label="重做"]');
  await waitFor(page, `${block}.rows[0].cells[0].checkboxOptions.length===2`);
  results.push({ test: 'blank payment checkbox options retain newlines, values and a single undo step', passed: true });

  await button('整张表');
  await select('快速版式', 'Blank');
  await waitFor(page, `${block}.columns.length===3`);
  await fill('行数', 5);
  await fill('列数', 7);
  await waitFor(page, `${block}.rows.length===5 && ${block}.columns.length===7`);
  await button('单元格');
  await fill('文字内容', '用款事项');
  // Multiline text is committed explicitly; ordinary Enter remains a newline.
  await key(page, 'Enter', 2);
  for (let index = 0; index < 4; index++) { await button('向下合并'); }
  await waitFor(page, `${block}.rows[0].cells[0].rowSpan===5`);
  const authored = await read(page, 'window.__designerHtml');
  await button('整张表');
  await fill('列数', 1);
  await waitFor(page, `${block}.columns.length===1`);
  assert.equal(await read(page, `${block}.rows.slice(1).every(row=>row.cells.length===0)`), true, 'covered rows may be empty');
  assert(await read(page, 'window.__designerDraftState.isValid'));
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(authored)}`);
  await fill('列数', 9);
  await waitFor(page, `${block}.columns.length===9 && ${block}.rows[0].cells[0].rowSpan===5`);
  await fill('列数', 15);
  await fill('行数', 7);
  await waitFor(page, `${block}.columns.length===15 && ${block}.rows.length===7`);
  await button('单元格');
  for (let index = 0; index < 4; index++) await button('拆分');
  await button('整张表');
  await select('快速版式', 'Blank');
  await fill('列数', 1);
  await button('单元格');
  await button('向下合并');
  await button('向下合并');
  await waitFor(page, `${block}.rows[0].cells[0].rowSpan===3 && ${block}.rows.slice(1).every(row=>row.cells.length===0)`);
  await button('拆分');
  await waitFor(page, `${block}.rows.every(row=>row.cells.length===1)`);
  assert(await read(page, 'window.__designerDraftState.isValid'));
  results.push({ test: 'blank grids set payment, expense and customs dimensions and merge entire covered rows', passed: true });
  await button('整张表');
  await select('快速版式', 'Blank');
  await button('单元格');
  await fill('文字内容', '通用登记表');
  await key(page, 'Enter', 2);
  await button('向右合并');
  await fill('单元格位置', 'A2');
  await button('向右合并');
  await fill('单元格位置', 'A1');
  await button('向下合并');
  await waitFor(page, `${block}.rows[0].cells[0].rowSpan===2 && ${block}.rows[0].cells[0].colSpan===2`);
  const mergedId = await read(page, `${block}.rows[0].cells[0].id`);
  const currentMerged = `${block}.rows.flatMap(row=>row.cells).find(cell=>cell.id===${JSON.stringify(mergedId)})`;
  const authoredGrid = await read(page, 'window.__designerHtml');
  await fill('单元格位置', 'C3');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'C3', 'one address must leave a merged header and reach the requested row and column together');
  await fill('单元格位置', '2，3');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'C2', 'numeric row,column entry supports a Chinese comma');
  await button('整张表');
  await button('上方插入行');
  await waitFor(page, `${block}.rows.length===4 && ${currentMerged}.rowSpan===3`);
  await fill('单元格位置', 'C2');
  await button('删除当前行');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(authoredGrid)}`);
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `${block}.rows.length===4`);
  await click(page, '[aria-label="重做"]');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(authoredGrid)}`);
  await fill('单元格位置', 'B3');
  await button('左侧插入列');
  await waitFor(page, `${block}.columns.length===4 && ${currentMerged}.colSpan===3`);
  await fill('单元格位置', 'B3');
  await button('删除当前列');
  await waitFor(page, `${block}.columns.length===3 && ${currentMerged}.colSpan===2`);
  assert.equal(await read(page, `${currentMerged}.text.trim()`), '通用登记表');
  results.push({ test: 'insert and delete middle rows and columns preserve spanning content and support undo', passed: true });

  await fill('单元格位置', 'A3');
  await button('单元格');
  const targetCellId = await read(page, `${block}.rows[2].cells[0].id`);
  const targetCell = `${block}.rows.flatMap(row=>row.cells).find(cell=>cell.id===${JSON.stringify(targetCellId)})`;
  const elementCount = await read(page, 'window.__designerSchema.layers.flatMap(layer=>layer.elements).length');
  const drop = async (cellId, label) => {
    await read(page, `(()=>{const source=document.querySelector('[aria-label="插入字段 '+${JSON.stringify(label)}+'"]');const cell=document.querySelector('[data-report-grid-cell-id="'+${JSON.stringify(cellId)}+'"]');const rect=cell.getBoundingClientRect();const dataTransfer=new DataTransfer();source.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer}));cell.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer,clientX:rect.left+rect.width/2,clientY:rect.top+rect.height/2}));})()`);
    await settle();
  };
  await drop(targetCellId, '收款方');
  await waitFor(page, `${targetCell}.fieldPath==='Payment.PayeeName' && ${targetCell}.contentKind==='Field'`);
  assert.equal(await read(page, 'window.__designerSchema.layers.flatMap(layer=>layer.elements).length'), elementCount);
  const bound = await read(page, 'window.__designerHtml');
  const boundUpdates = await read(page, 'window.__designerUpdates');
  await drop(targetCellId, '收款方');
  assert.equal(await read(page, 'window.__designerUpdates'), boundUpdates, 'same binding must not publish a second draft');
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `${targetCell}.contentKind==='Text'`);
  await click(page, '[aria-label="重做"]');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(bound)}`);
  await select('内容类型', 'CheckboxGroup');
  await focus('勾选项（每行：名称=值）');
  await page.send('Input.insertText', { text: '电汇=电汇' });
  await key(page, 'Enter', 2);
  await drop(targetCellId, '付款方式');
  await waitFor(page, `${targetCell}.contentKind==='CheckboxGroup' && ${targetCell}.fieldPath==='Payment.PaymentMethod'`);
  assert.equal(await read(page, `${targetCell}.checkboxOptions[0].value`), '电汇');
  results.push({ test: 'drag fields directly into fixed and checkbox cells without adding overlays or losing options', passed: true });
  fs.writeFileSync(path.join(output, 'blank-grid-authored.json'), await read(page, 'window.__designerHtml'));
  await captureScreenshot(page, path.join(output, 'blank-grid-authoring.png'));

  await button('整张表');
  await select('快速版式', 'Blank');
  await fill('行数', 40);
  await fill('列数', 30);
  await waitFor(page, `${block}.rows.length===40 && ${block}.columns.length===30`);
  const navigationUpdates = await read(page, 'window.__designerUpdates');
  await fill('单元格位置', 'AC39');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'AC39');
  await fill('单元格位置', 'ZZ999');
  await waitFor(page, 'document.querySelector("[aria-label=定位表格单元格] [role=alert]")');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'AC39', 'invalid addresses preserve the selection');
  assert.equal(await read(page, 'window.__designerUpdates'), navigationUpdates, 'navigation must not serialize a large template');
  assert.equal(await read(page, 'document.querySelectorAll("[aria-label=定位表格单元格] button").length'), 2);
  assert.equal(await read(page, 'document.querySelectorAll("[data-grid-picker-cell]").length'), 0, 'the inspector must not mount a second full grid');
  results.push({ test: '1200-cell grids use constant-sized navigation without publishing drafts', passed: true });

  await page.send('Page.navigate', { url: `${url}?blank=1` });
  await waitFor(page, 'document.querySelector("[data-v3-page-canvas]") && window.__designerDraftState');
  await read(page, `document.querySelector('.report-designer-v3-toolbar details').open=true`);
  await click(page, '[aria-label="普通表格"]');
  const emptyCell = await read(page, `${block}.rows[0].cells[0].id`);
  const beforeInvalidDrop = await read(page, 'window.__designerHtml');
  await click(page, '[aria-label="商品字段"]');
  await drop(emptyCell, '明细备用 1');
  await waitFor(page, 'document.querySelector(".report-designer-v3-notice")?.textContent.includes("商品循环外")');
  assert.equal(await read(page, 'window.__designerHtml'), beforeInvalidDrop);
  await select('内容类型', 'Field');
  assert(await read(page, `[...${control('业务字段')}.options].every(option=>!option.value.startsWith('item.'))`));
  results.push({ test: 'fixed grids refuse item fields and offer only fields with an available data context', passed: true });

  await page.send('Page.navigate', { url: `${url}?blank=1&payment=1` });
  await waitFor(page, 'document.querySelector("[data-v3-page-canvas]") && window.__designerDraftState');
  assert(await read(page, 'document.querySelector("[aria-label=普通表格]").getClientRects().length>0'), 'ordinary tables are directly available on the toolbar');
  await click(page, '[aria-label="普通表格"]');
  await fill('文字内容', '通用报表标题'); await key(page, 'Enter', 2);
  await fill('单元格位置', 'B1');
  await fill('文字内容', '另一个标题'); await key(page, 'Enter', 2);
  await select('字号', '17');
  const beforeConflict = await read(page, 'window.__designerHtml');
  const selectionUpdates = await read(page, 'window.__designerUpdates');
  await read(page, 'window.__rangeCell=document.querySelector("[data-report-grid-cell-id]")');
  await fill('单元格位置', 'A1:C2');
  await waitFor(page, 'document.querySelectorAll(".is-designer-selected-cell").length===6');
  assert.equal(await read(page, 'window.__designerUpdates'), selectionUpdates, 'range selection must not publish or serialize the template');
  assert(await read(page, 'window.__rangeCell===document.querySelector("[data-report-grid-cell-id]")'), 'range highlighting retains the table DOM');
  await button('合并所选区域');
  await waitFor(page, 'document.querySelector(".new-report-grid-properties [role=alert]")?.textContent.includes("多份内容")');
  assert.equal(await read(page, 'window.__designerHtml'), beforeConflict, 'conflicting text and fields survive a refused merge');
  await fill('单元格位置', 'B1');
  await focus('文字内容'); await key(page, 'Backspace');
  await waitFor(page, `${control('文字内容')}.value===''`);
  await key(page, 'Enter', 2);
  await waitFor(page, `${block}.rows[0].cells[1].text===''`);
  await fill('单元格位置', 'A1:C2');
  const beforeFormat = await read(page, 'window.__designerHtml');
  await select('对齐', 'Center');
  await waitFor(page, `${block}.rows.slice(0,2).every(row=>row.cells.every(cell=>cell.style.align==='Center'))`);
  assert.equal(await read(page, `${block}.rows[0].cells[1].style.fontSizePt`), 17, 'batch alignment preserves each cell font size');
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(beforeFormat)}`);
  await click(page, '[aria-label="重做"]');
  await button('仅外框');
  await waitFor(page, `${block}.rows[0].cells[0].border.top && !${block}.rows[0].cells[0].border.bottom && ${block}.rows[1].cells[2].border.right`);
  await button('清除框线');
  assert.equal(await read(page, `${block}.rows[2].cells[0].border.top`), false, 'clearing a range removes the opposite shared border');
  await button('全部框线');
  const beforeMerge = await read(page, 'window.__designerHtml');
  await button('合并所选区域');
  await waitFor(page, `${block}.rows[0].cells[0].rowSpan===2 && ${block}.rows[0].cells[0].colSpan===3`);
  assert.equal(await read(page, `${block}.rows[0].cells[0].text.trim()`), '通用报表标题');
  await click(page, '[aria-label="撤销"]');
  await waitFor(page, `window.__designerHtml===${JSON.stringify(beforeMerge)}`);
  results.push({ test: 'range merge refuses content loss, preserves the sole content and undoes in one step', passed: true });
  results.push({ test: 'range style changes only the requested property and shares collapsed borders', passed: true });

  await fill('单元格位置', 'A1');
  const beforeShift = await read(page, 'window.__designerHtml');
  await read(page, `(()=>{const id=${block}.rows[1].cells[2].id;document.querySelector('[data-report-grid-cell-id="'+id+'"]').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,pointerId:79,shiftKey:true}));})()`);
  await waitFor(page, 'document.querySelectorAll(".is-designer-selected-cell").length===6');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'A1:C2');
  assert.equal(await read(page, 'document.querySelectorAll("[data-v3-element-id].is-selected").length'), 1, 'Shift selects cells without toggling the table selection');
  assert.equal(await read(page, 'window.__designerHtml'), beforeShift, 'Shift selection never starts a table drag');
  fs.writeFileSync(path.join(output, 'grid-range-authored.json'), await read(page, 'window.__designerHtml'));
  await captureScreenshot(page, path.join(output, 'grid-range-authoring.png'));
  await fill('单元格位置', 'D99:F100');
  assert.equal(await read(page, `${control('单元格位置')}.value`), 'A1:C2');
  results.push({ test: 'Shift-click and address ranges select cells without rebuilding DOM or publishing drafts', passed: true });
}
