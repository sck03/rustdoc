import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspace = path.join(repoRoot, ".codex-runtime", "authentication-failure-event-tests");
const entry = path.join(workspace, "entry.ts");
const bundle = path.join(workspace, "bundle.mjs");
fs.rmSync(workspace, { recursive: true, force: true });
fs.mkdirSync(workspace, { recursive: true });

const modelPath = path.join(repoRoot, "apps", "export-doc-web", "src", "api", "authenticationFailureEvents.ts").replaceAll("\\", "/");
const apiPath = path.join(repoRoot, "apps", "export-doc-web", "src", "api", "index.ts").replaceAll("\\", "/");
const sessionClientPath=path.join(repoRoot,"apps","export-doc-web","src","app","sessionApiClient.ts").replaceAll("\\","/");
fs.writeFileSync(entry, `import * as model from ${JSON.stringify(modelPath)}; import { ApiError } from ${JSON.stringify(apiPath)}; import { createSessionApiClient } from ${JSON.stringify(sessionClientPath)}; globalThis.__model = { ...model, ApiError, createSessionApiClient };`, "utf8");
const esbuild = require(path.join(repoRoot, "apps", "export-doc-web", "node_modules", "esbuild"));
await esbuild.build({ entryPoints: [entry], outfile: bundle, bundle: true, format: "esm", platform: "node", logLevel: "silent" });
await import(pathToFileURL(bundle).href);

const { ApiError, notifyAuthenticationFailure, subscribeToAuthenticationFailure } = globalThis.__model;
const assert = (condition, message) => { if (!condition) throw new Error(message); };
let notifications = 0;
const unsubscribe = subscribeToAuthenticationFailure(() => { notifications += 1; });

assert(!notifyAuthenticationFailure(new ApiError(403, "Forbidden", "")), "403 must remain a permission error");
assert(!notifyAuthenticationFailure(new ApiError(409, "Conflict", "")), "409 must remain a business conflict");
assert(notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "401 should schedule logout");
assert(!notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "simultaneous 401 responses should be coalesced");
await new Promise((resolve) => setTimeout(resolve, 0));
assert(notifications === 1, "coalesced 401 responses should notify once");
unsubscribe();
assert(notifyAuthenticationFailure(new ApiError(401, "Unauthorized", "")), "401 should still be recognized without listeners");
await new Promise((resolve) => setTimeout(resolve, 0));
assert(notifications === 1, "unsubscribed listener must not run");
const {createSessionApiClient}=globalThis.__model;
let current=true, failures=0, resolveResponse, signalStarted;
let requestStarted=new Promise(resolve=>{signalStarted=resolve;});
const releaseListener=subscribeToAuthenticationFailure(()=>{failures+=1;});
const unauthorized=()=>new Response(JSON.stringify({message:"会话已过期"}),{status:401,headers:{"content-type":"application/json"}});
const delayedFetch=()=>new Promise(resolve=>{resolveResponse=resolve;signalStarted();});
const oldClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"old-session",fetch:delayedFetch},()=>current);
const staleRequest=oldClient.getCurrentUser().catch(()=>{});
await requestStarted;
current=false;resolveResponse(unauthorized());await staleRequest;await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===0,"a late 401 from the previous session must not end its replacement");
const validClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"current-session",fetch:async()=>unauthorized()},()=>true);
await validClient.getCurrentUser().catch(()=>{});await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===1,"an authentication failure from the active session must be reported");
const abort=new AbortController();
requestStarted=new Promise(resolve=>{signalStarted=resolve;});
const abortedClient=createSessionApiClient({baseUrl:"http://localhost",accessToken:"current-session",fetch:delayedFetch},()=>true);
const abortedRequest=abortedClient.getCurrentUser({signal:abort.signal}).catch(()=>{});
await requestStarted;
abort.abort();resolveResponse(unauthorized());await abortedRequest;await new Promise(resolve=>setTimeout(resolve,0));
assert(failures===1,"an aborted request must not invalidate an active session");
releaseListener();
process.stdout.write("authentication failure event tests passed\n");
