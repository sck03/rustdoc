// Focused React -> HTTP verification of first deployment and independent service editing.
import assert from 'node:assert/strict';
import path from 'node:path';
import { withOfficeUi } from './lib/native-office-ui.mjs';
import { approvalStage, linkBusinessPerson, saveApprovalSettings } from './lib/approval-fixtures.mjs';

await withOfficeUi('oa-deployment-ui', async ({ output, url, invoke, openPage }) => {
  const token=(await invoke('Login',{username:'oa-review',password:'Review-2026-Test'})).accessToken;
  const reviewer=(await invoke('createUserAccount',{username:'deploy-reviewer',fullName:'部署审批员',role:'OfficeEmployee',companyScope:'DEFAULT',departmentId:'GENERAL',isActive:true,resetPassword:'Review-2026-Test',permissionGrants:['view','approve','complete'].map(action=>({resourceKey:'office.general',action,dataScope:'company'}))},{},token)).user;
  await linkBusinessPerson(invoke,token,reviewer);
  const settings=await invoke('GetOaApprovalSettings',undefined,{},token);
  settings.rules.find(rule=>rule.key==='general').stages=[approvalStage('review',[reviewer.id])];
  await saveApprovalSettings(invoke,token,settings);
  const page=await openPage('oa-review','Review-2026-Test');
  await page.goto(`${url}/#/office/approval-settings`);
  await page.getByText('首次启用流程',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'办理分工',exact:true}).click();
  await page.getByRole('button',{name:'添加办理事项',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'添加办理事项',exact:true});
  await dialog.getByLabel('事项名称',{exact:true}).fill('合同公章');
  await dialog.getByLabel('办理人员 1',{exact:true}).selectOption(String(reviewer.id));
  await dialog.getByRole('button',{name:'保存事项',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.getByRole('table',{name:'办理事项目录'}).getByText('合同公章',{exact:true}).waitFor();
  await page.getByLabel('搜索事项',{exact:true}).fill('合同');
  const row=page.getByRole('table',{name:'办理事项目录'}).getByRole('row').filter({hasText:'合同公章'});
  await row.getByRole('button',{name:'编辑',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'编辑办理事项',exact:true});
  await dialog.getByLabel('事项名称',{exact:true}).fill('合同用印');
  await dialog.getByRole('button',{name:'保存事项',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.getByRole('tab',{name:'流程定义',exact:true}).click();
  await page.getByRole('button',{name:'批量发布',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'批量发布流程',exact:true});
  await dialog.getByRole('button',{name:'清空',exact:true}).click();
  await dialog.getByRole('checkbox',{name:settings.rules.find(rule=>rule.key==='general').name,exact:true}).check();
  await dialog.getByRole('button',{name:'选择人员任职',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'选择部门负责人',exact:true});
  await picker.getByRole('textbox',{name:'按姓名或工号搜索负责人'}).fill('李明');
  await picker.getByRole('button',{name:'搜索',exact:true}).click();
  await picker.getByRole('button').filter({hasText:'李明'}).click();
  await picker.waitFor({state:'hidden'});
  await dialog.getByRole('button',{name:'批量预检',exact:true}).click();
  await dialog.getByRole('cell',{name:'可执行',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'deployment-preview.png'),fullPage:true});
  await dialog.getByRole('button',{name:'确认发布 1 个流程',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert((await invoke('GetOaApprovalSettings',undefined,{},token)).publications.some(p=>p.key==='general'&&p.enabled));
  await page.getByRole('button',{name:'批量停用',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'批量停用流程',exact:true});
  await dialog.getByText('所选流程停止接收新申请，在途申请继续按原发布版本办理。',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'批量预检',exact:true}).click();
  await dialog.getByRole('button',{name:'确认停用 1 个流程',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert((await invoke('GetOaApprovalSettings',undefined,{},token)).publications.every(p=>!p.enabled));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'deployment-mobile.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'The page must fit the narrow viewport');
});
