CREATE FUNCTION exportdoc_sync_personnel_memberships() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind='people' THEN
        DELETE FROM personnel_memberships WHERE person_id=NEW.id;
        INSERT INTO personnel_memberships VALUES(NEW.id,NEW.company,NEW.department,COALESCE(NEW.body->>'jobTitle',''),COALESCE(NULLIF(NEW.body->'organization'->>'primaryStartsOn',''),NEW.body->>'hireDate',''),'',1,NEW.body->'organization'->>'primaryAssignmentId',(SELECT id FROM organization_units WHERE code=NEW.company),(SELECT d.id FROM organization_departments d JOIN organization_units u ON u.id=d.unit_id WHERE u.code=NEW.company AND d.code=NEW.department));
        INSERT INTO personnel_memberships SELECT NEW.id,COALESCE(NULLIF(a->>'companyCode',''),NEW.company),a->>'departmentId',COALESCE(a->>'jobTitle',''),COALESCE(a->>'startsOn',''),COALESCE(a->>'endsOn',''),0,a->>'id',(SELECT id FROM organization_units WHERE code=COALESCE(NULLIF(a->>'companyCode',''),NEW.company)),(SELECT d.id FROM organization_departments d JOIN organization_units u ON u.id=d.unit_id WHERE u.code=COALESCE(NULLIF(a->>'companyCode',''),NEW.company) AND d.code=a->>'departmentId') FROM jsonb_array_elements(COALESCE(NULLIF(NEW.body->'organization'->'additionalAssignments','null'::jsonb),'[]'::jsonb)) a;
        INSERT INTO reporting_relations SELECT NEW.body->'organization'->>'primaryAssignmentId',NEW.body->'organization'->>'managerAssignmentId','Line' WHERE NEW.body->'organization'->>'managerAssignmentId' IS NOT NULL;
        INSERT INTO reporting_relations SELECT NEW.body->'organization'->>'primaryAssignmentId',f,'Functional' FROM jsonb_array_elements_text(COALESCE(NULLIF(NEW.body->'organization'->'functionalManagerAssignmentIds','null'::jsonb),'[]'::jsonb)) f;
        INSERT INTO reporting_relations SELECT a->>'id',a->>'managerAssignmentId','Line' FROM jsonb_array_elements(COALESCE(NULLIF(NEW.body->'organization'->'additionalAssignments','null'::jsonb),'[]'::jsonb)) a WHERE a->>'managerAssignmentId' IS NOT NULL;
        INSERT INTO reporting_relations SELECT a->>'id',f,'Functional' FROM jsonb_array_elements(COALESCE(NULLIF(NEW.body->'organization'->'additionalAssignments','null'::jsonb),'[]'::jsonb)) a CROSS JOIN LATERAL jsonb_array_elements_text(COALESCE(NULLIF(a->'functionalManagerAssignmentIds','null'::jsonb),'[]'::jsonb)) f;
    END IF;
    RETURN NEW;
END $$;
