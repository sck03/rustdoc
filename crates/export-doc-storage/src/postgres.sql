CREATE FUNCTION exportdoc_sync_identity_relations() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind='people' THEN
        DELETE FROM personnel_accounts WHERE person_id=NEW.id;
        INSERT INTO personnel_accounts SELECT NEW.id,NULLIF(NEW.body->'account'->>'id','')::BIGINT WHERE NULLIF(NEW.body->'account'->>'id','')::BIGINT IS NOT NULL;
    ELSIF NEW.kind='permission-templates' THEN
        INSERT INTO permission_schemes VALUES(NEW.id,(NEW.body->>'ownerUnitId')::BIGINT,NEW.body->>'code') ON CONFLICT(id) DO UPDATE SET owner_unit_id=excluded.owner_unit_id,code=excluded.code;
    ELSIF NEW.kind IN ('companies','departments') THEN
        DELETE FROM organization_duties WHERE organization_id=NEW.id;
        INSERT INTO organization_duties SELECT NEW.id,COALESCE(NEW.body->>'executiveAppointmentId',NEW.body->>'managerAppointmentId'),'Primary','[]'::jsonb WHERE COALESCE(NEW.body->>'executiveAppointmentId',NEW.body->>'managerAppointmentId') IS NOT NULL;
        INSERT INTO organization_duties SELECT NEW.id,a->>'appointmentId','Delegate',a->'workflowKinds' FROM jsonb_array_elements(COALESCE(NULLIF(NEW.body->'additionalLeaders','null'::jsonb),'[]'::jsonb)) a;
    ELSIF NEW.kind='unit-access' THEN
        INSERT INTO unit_access_roles VALUES(NEW.id,(NEW.body->>'userId')::BIGINT,(SELECT id FROM organization_units WHERE code=NEW.body->>'companyCode'),NULLIF(NEW.body->>'appointmentId',''),NEW.body->>'mode',CASE WHEN (NEW.body->>'isActive')::boolean THEN 1 ELSE 0 END,(NEW.body->>'permissionTemplateId')::BIGINT,(NEW.body->>'authorityRoleId')::BIGINT) ON CONFLICT(id) DO UPDATE SET user_id=excluded.user_id,unit_id=excluded.unit_id,appointment_id=excluded.appointment_id,mode=excluded.mode,is_active=excluded.is_active,template_id=excluded.template_id,authority_role_id=excluded.authority_role_id;
        DELETE FROM unit_access_grants WHERE role_id=NEW.id;
        INSERT INTO unit_access_grants SELECT NEW.id,g->>'resourceKey',g->>'action',g->>'dataScope' FROM jsonb_array_elements(COALESCE(NULLIF(NEW.body->'permissionGrants','null'::jsonb),'[]'::jsonb)) g;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER identity_relations_sync AFTER INSERT OR UPDATE OF body ON records FOR EACH ROW EXECUTE FUNCTION exportdoc_sync_identity_relations();
