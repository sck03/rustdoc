CREATE FUNCTION exportdoc_sync_organization() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind='companies' THEN INSERT INTO organization_units(id,code,parent_id,unit_kind) VALUES(NEW.id,NEW.body->>'code',CASE WHEN COALESCE(NEW.body->>'parentCompanyCode','')='' THEN NULL ELSE COALESCE((SELECT id FROM organization_units WHERE code=NEW.body->>'parentCompanyCode'),-1) END,COALESCE(NEW.body->>'unitKind','Company')) ON CONFLICT(id) DO UPDATE SET parent_id=excluded.parent_id,unit_kind=excluded.unit_kind,code=excluded.code;
    ELSIF NEW.kind='departments' THEN INSERT INTO organization_departments(id,unit_id,code,parent_id) VALUES(NEW.id,COALESCE((SELECT id FROM organization_units WHERE code=NEW.body->>'companyCode'),-1),NEW.body->>'code',CASE WHEN COALESCE(NEW.body->>'parentCode','')='' THEN NULL ELSE COALESCE((SELECT d.id FROM organization_departments d JOIN organization_units u ON u.id=d.unit_id WHERE u.code=NEW.body->>'companyCode' AND d.code=NEW.body->>'parentCode'),-1) END) ON CONFLICT(id) DO UPDATE SET code=excluded.code,unit_id=excluded.unit_id,parent_id=excluded.parent_id;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER organization_sync AFTER INSERT OR UPDATE OF body ON records FOR EACH ROW EXECUTE FUNCTION exportdoc_sync_organization();
CREATE TABLE personnel_memberships (
    person_id BIGINT NOT NULL REFERENCES records(id) ON DELETE CASCADE,
    company TEXT NOT NULL, department TEXT NOT NULL, job_title TEXT NOT NULL,
    starts_on TEXT NOT NULL, ends_on TEXT NOT NULL, is_primary SMALLINT NOT NULL CHECK(is_primary IN (0,1)),
