import assert from "node:assert/strict";
export async function verifyDesignerUsability({ page, url, read, waitFor, click, key, results }) {
  await page.send("Page.navigate", { url: `${url}?editing=1` });
  await waitFor(page, 'document.querySelector("[data-v3-element-id=edit-text]")');
  await click(page, '.report-designer-v3-sidebar-tabs button:nth-child(3)');
  await read(page, `(() => {const input=document.querySelector('[aria-label="搜索已放置的内容"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'目标文本');input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  await waitFor(page, 'document.querySelectorAll(".report-designer-v3-layer-elements button").length===1');
  await click(page, '.report-designer-v3-layer-elements button');
  await waitFor(page, 'document.querySelector("[data-v3-element-id=edit-other]").getAttribute("aria-current")==="true"');
  results.push({ test: 'object search locates content across layers', passed: true });
  await click(page, '.report-designer-v3-toolbar button[title^="开启后"]');
  await read(page, `document.querySelector('[data-v3-element-id=edit-text]').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,pointerId:80}));`);
  await waitFor(page, 'document.querySelectorAll(".report-designer-v3-element.is-selected").length===2');
  assert.equal(await read(page, 'window.__designerDraftState.isDirty'), false, 'touch multiselect only changes selection');
  await click(page, 'button[aria-label="左对齐"]');
  await waitFor(page, 'window.__designerDraftState.isDirty');
  const aligned = await read(page, 'window.__designerSchema.layers.flatMap(l=>l.elements).filter(e=>["edit-text","edit-other"].includes(e.id)).map(e=>e.xHundredthMm)');
  assert.equal(aligned[0], aligned[1]);
  await click(page, 'button[aria-label="撤销"]');
  await waitFor(page, '!window.__designerDraftState.isDirty');
  results.push({ test: 'touch multiselect aligns in one reversible operation', passed: true });
  await click(page, 'button[aria-label="左对齐"]');
  await waitFor(page, 'window.__designerDraftState.isDirty');
  const draft = await read(page, 'window.__designerHtml');
  const reload = () => read(page, `[...document.querySelectorAll('button')].find(e=>e.textContent.trim()==='重新载入').click()`);
  await reload();
  await waitFor(page, 'document.querySelector(".confirmation-dialog")');
  await read(page, `[...document.querySelectorAll('.confirmation-dialog button')].find(e=>e.textContent.trim()==='取消').click()`);
  assert.equal(await read(page, 'window.__designerHtml'), draft);
  await reload();
  await waitFor(page, 'document.querySelector(".confirmation-dialog")');
  await read(page, `[...document.querySelectorAll('.confirmation-dialog button')].find(e=>e.textContent.trim()==='放弃修改并载入').click()`);
  await waitFor(page, '!window.__designerDraftState.isDirty');
  results.push({ test: 'reload requires explicit discard and cancellation preserves draft', passed: true });
  await page.send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await waitFor(page, 'document.querySelector(".report-designer-v3-canvas-column").getClientRects().length>0');
  await click(page, '.report-designer-v3-compact-tabs button:nth-child(1)');
  await waitFor(page, 'document.querySelector(".report-designer-v3-sidebar").getClientRects().length>0');
  assert.equal(await read(page, 'document.querySelector(".report-designer-v3-canvas-column").getClientRects().length'), 0);
  await click(page, '.report-designer-v3-compact-tabs button:nth-child(3)');
  await waitFor(page, 'document.querySelector(".report-designer-v3-inspector").getClientRects().length>0');
  await click(page, '.report-designer-v3-compact-tabs button:nth-child(2)');
  await waitFor(page, 'document.querySelector(".report-designer-v3-page-frame").getBoundingClientRect().width <= document.querySelector(".report-designer-v3-canvas-scroll").clientWidth');
  const updates = await read(page, 'window.__designerUpdates');
  await read(page, `(() => {const select=document.querySelector('[aria-label="选择缩放比例"]');select.value='100';select.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await waitFor(page, 'document.querySelector(".report-designer-v3-zoom-readout").textContent==="100%"');
  await page.send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await key(page, 'Escape');
  assert.equal(await read(page, 'document.querySelector(".report-designer-v3-zoom-readout").textContent'), '100%');
  assert.equal(await read(page, 'window.__designerUpdates'), updates, 'view changes never serialize or dirty the draft');
  await click(page, 'button[aria-label="适合窗口"]');
  await waitFor(page, 'document.querySelector(".report-designer-v3-zoom-readout").textContent!=="100%"');
  results.push({ test: 'compact panels preserve the editor and manual zoom survives resize', passed: true });
}
