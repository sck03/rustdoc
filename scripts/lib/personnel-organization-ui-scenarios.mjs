import assert from "node:assert/strict";
import path from "node:path";

export async function runPersonnelOrganizationUi({page,open,read,waitFor,clickText,input,audit,results,output,captureScreenshot}) {
  for (const width of [1440,390,320]) {
    await open("organization",width,"complex");
    const initialCount=await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length");
    assert(initialCount>20&&initialCount<50,"complex organizations start with two levels, not every descendant");
    if(width===1440)assert(await read(page,"[...document.querySelectorAll('.organization-tree-table tbody tr')].every(row=>row.getBoundingClientRect().height<=48)"),"desktop department rows must stay compact");
    await audit(page,`organization-complex-${width}`);
    await captureScreenshot(page,path.join(output,`organization-complex-${width}.png`));
    await clickText(page,"全部展开");
    assert.equal(await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length"),175);
    await clickText(page,"仅看一级");
    assert.equal(await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length"),5);
    await input(page,'input[aria-label="查找部门或负责人"]',"重点客户协作组");
    assert.equal(await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length"),3);
    await clickText(page,"重点客户协作组AREA-2-TEAM-3-GROUP-2",".organization-node-name");
    assert(await read(page,"document.querySelector('.organization-selection-path').textContent.includes('示例公司 / 业务事业部2 / 区域团队3 / 重点客户协作组')"));
    await input(page,'input[aria-label="查找部门或负责人"]',"DEEP-19");
    assert.equal(await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length"),21);
    await read(page,"document.querySelector('.organization-tree-table tbody tr:last-child .organization-node-name').click()");
    assert(await read(page,"document.querySelector('.organization-selection-path').textContent.includes('专项组19')"));
    await audit(page,`organization-deep-search-${width}`);
    await input(page,'input[aria-label="查找部门或负责人"]',"");
    assert.equal(await read(page,"document.querySelectorAll('.organization-tree-table tbody tr').length"),5,"clearing search restores the user's collapse choice");
    if(width===1440) {
      await clickText(page,"展开两级");
      await read(page,"document.querySelector('[data-department-code=AREA-1-TEAM-1] [aria-label=为区域团队1新增下级部门]').click()");
      await input(page,'input[name="code"]',"FRESH-TEAM");await input(page,'input[name="name"]',"新增三级部门");await clickText(page,"保存部门");
      await waitFor(page,"!document.querySelector('.office-dialog') && document.querySelector('[data-department-code=FRESH-TEAM]')?.dataset.selected==='true'");
      assert(await read(page,"document.querySelector('.organization-selection-path').textContent.includes('区域团队1 / 新增三级部门')"));
      results.push("organization-save-reveals-descendant");
    }
    if(width===1440)await read(page,"[...document.querySelectorAll('.organization-company-list button')].find(button=>button.textContent.includes('华东分公司')).click()");
    else await input(page,'.organization-company-switch select',"BRANCH");
    await waitFor(page,"document.body.innerText.includes('该公司尚未设置部门')");
    results.push(`organization-complex-search-collapse-switch-${width}`);
  }
  for (const width of [1024,390,320]) {
    await open("organization",width);
    await audit(page,`organization-${width}`);
    await captureScreenshot(page,path.join(output,`organization-${width}.png`));
    await clickText(page,"新增部门");
    await audit(page,`organization-department-form-${width}`);
    await input(page,'input[name="code"]',"SALES-TEAM");
    await input(page,'input[name="name"]',"华东业务组");
    await input(page,'select[name="parentCode"]',"D1");
    await clickText(page,"选择负责人");
    await waitFor(page,"document.querySelector('.organization-managers button')");
    await audit(page,`organization-manager-picker-${width}`);
    await read(page,"document.querySelector('.organization-managers button').click()");
    await clickText(page,"保存部门");
    await waitFor(page,"!document.querySelector('.office-dialog') && document.body.innerText.includes('华东业务组')");
    const created=await read(page,"window.__officeCalls.find(item=>item.name==='createDepartment').input.body");
    assert.equal(created.parentCode,"D1");assert.equal(created.managerEmployeeId,1);
    await audit(page,`organization-tree-with-manager-${width}`);
    await captureScreenshot(page,path.join(output,`organization-tree-with-manager-${width}.png`));
    await clickText(page,"人员档案","a");
    await waitFor(page,"document.querySelector('.personnel-card')");
    await clickText(page,"入职登记");
    assert(await read(page,"[...document.querySelector('select[name=departmentId]').options].some(item=>item.value==='SALES-TEAM'&&item.textContent==='业务部 / 华东业务组')"));
    results.push(`organization-personnel-options-refresh-${width}`);
  }
  await open("organization",1024);
  await clickText(page,"编辑公司");await input(page,'input[name="name"]',"实际公司名称");await clickText(page,"保存公司");
  await waitFor(page,"!document.querySelector('.office-dialog') && document.body.innerText.includes('实际公司名称')");
  assert.equal((await read(page,"window.__officeCalls.find(item=>item.name==='updateCompany').input")).body.expectedVersion,1);
  results.push("organization-company-edit-version");
  await read(page,"document.querySelector('[aria-label=编辑业务部]').click()");
  await clickText(page,"选择负责人");await waitFor(page,"document.querySelector('.organization-managers button')");
  await read(page,"document.querySelector('.organization-managers button').click()");
  await read(page,"document.querySelector('.office-dialog [aria-label=关闭窗口]').click()");
  await waitFor(page,"document.body.innerText.includes('放弃未提交的内容')");
  results.push("organization-manager-selection-unsaved-guard");
  await open("people",390);
  assert(await read(page,"Boolean(document.querySelector('a[href*=organization]'))"));
  await clickText(page,"人员档案");await waitFor(page,"document.querySelector('.personnel-facts')");
  assert.equal(await read(page,"document.querySelector('.personnel-facts').innerText.includes('11010519491231002X')"),false);
  await clickText(page,"查看完整号码");assert(await read(page,"document.querySelector('.personnel-facts').innerText.includes('11010519491231002X')"));
  await clickText(page,"隐藏号码");results.push("identity-number-masked-and-explicit-reveal");
  await clickText(page,"编辑档案");await clickText(page,"个人资料与人事备注（限人事档案权限）","summary");
  await waitFor(page,"document.querySelector('input[name=identityNumber]')");
  assert(await read(page,"document.querySelector('input[name=identityValidUntil]').disabled"));
  await input(page,'input[name="identityAuthority"]',"更新后的签发机关");
  await audit(page,"personnel-private-identity-form");
  await clickText(page,"保存档案");await waitFor(page,"!document.querySelector('input[name=identityNumber]')");
  const profile=await read(page,"window.__officeCalls.find(item=>item.name==='updatePerson').input.body.profile");
  assert.equal(profile.identityAuthority,"更新后的签发机关");assert.equal(profile.identityValidUntil,null);assert(profile.identityLongTerm);
  await clickText(page,"照片与证件");await waitFor(page,"document.querySelector('.personnel-images')");
  await audit(page,"personnel-empty-images-mobile");
  const chooseFile=async(index,color)=>{
    await read(page,`new Promise(resolve=>{const canvas=document.createElement('canvas');canvas.width=160;canvas.height=100;const context=canvas.getContext('2d');context.fillStyle=${JSON.stringify(color)};context.fillRect(0,0,160,100);canvas.toBlob(blob=>{const transfer=new DataTransfer();transfer.items.add(new File([blob],'photo.png',{type:'image/png'}));const input=document.querySelectorAll('input[type=file]')[${index}];input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));resolve(true)},'image/png')})`);
  };
  await chooseFile(0,"#14607a");await waitFor(page,"document.querySelector('.personnel-image-preview img')?.naturalWidth>0");
  await clickText(page,"档案信息");await waitFor(page,"document.body.innerText.includes('放弃未上传的图片')");
  await clickText(page,"取消",".confirmation-dialog button");
  await clickText(page,"上传图片",".personnel-image-card:first-child button");
  await waitFor(page,"window.__officeCalls.some(item=>item.name==='uploadImage') && !document.body.innerText.includes('待保存：')");
  await chooseFile(1,"#b8dbd5");await clickText(page,"上传图片",".personnel-image-card:nth-child(2) button");
  await waitFor(page,"window.__officeCalls.filter(item=>item.name==='uploadImage').length===2 && !document.body.innerText.includes('待保存：')");
  await chooseFile(2,"#d8c09a");await clickText(page,"上传图片",".personnel-image-card:nth-child(3) button");
  await waitFor(page,"window.__officeCalls.filter(item=>item.name==='uploadImage').length===3 && !document.body.innerText.includes('待保存：')");
  assert(await read(page,"[...document.querySelectorAll('.personnel-image-preview img')].every(item=>item.naturalWidth===160)"));
  await audit(page,"personnel-three-images-mobile");await captureScreenshot(page,path.join(output,"personnel-three-images-mobile.png"));
  await read(page,"document.querySelector('.personnel-image-preview').click()");await waitFor(page,"document.querySelector('.personnel-image-zoom')");
  await audit(page,"personnel-image-zoom");
  await read(page,"[...document.querySelectorAll('.office-dialog [aria-label=关闭窗口]')].at(-1).click()");
  await chooseFile(0,"#303f68");await clickText(page,"替换图片",".personnel-image-card:first-child button");
  await waitFor(page,"window.__officeCalls.filter(item=>item.name==='uploadImage').length===4 && !document.body.innerText.includes('待保存：')");
  const uploads=await read(page,"window.__officeCalls.filter(item=>item.name==='uploadImage').map(item=>item.input)");
  assert.deepEqual(uploads.map(item=>item.kind),["Avatar","IdentityFront","IdentityBack","Avatar"]);
  assert(uploads.every((item,index)=>index===0||item.expectedVersion>uploads[index-1].expectedVersion));
  await clickText(page,"移除图片",".personnel-image-card:nth-child(3) button");
  await waitFor(page,"document.body.innerText.includes('移除身份证国徽面')");await clickText(page,"移除图片",".confirmation-dialog button");
  await waitFor(page,"window.__officeCalls.some(item=>item.name==='deleteImage')");results.push("personnel-image-upload-replace-delete-concurrency");
  await clickText(page,"档案信息");await read(page,"document.querySelector('.office-dialog [aria-label=关闭窗口]').click()");
  await waitFor(page,"!document.querySelector('.office-dialog') && document.querySelector('.personnel-avatar')?.naturalWidth>0");
  await audit(page,"personnel-avatar-in-directory");
  await open("people",390,"employee");
  assert.equal(await read(page,"document.body.innerText.includes('身份证') || Boolean(document.querySelector('a[href*=organization]'))"),false);
  assert.equal(await read(page,"window.__officeCalls.some(item=>item.name==='readImage')"),false);results.push("personnel-private-image-directory-isolation");
  await open("organization",390);await read(page,"document.querySelector('[aria-label=编辑业务部]').click()");
  await clickText(page,"选择负责人");await waitFor(page,"document.querySelector('.organization-managers button')");
  await read(page,"document.querySelector('.organization-managers button').click()");await clickText(page,"保存部门");
  await waitFor(page,"!document.querySelector('.office-dialog')");await clickText(page,"人员档案","a");
  await waitFor(page,"document.querySelector('.personnel-card')");await clickText(page,"人员档案");await waitFor(page,"document.querySelector('.personnel-facts')");
  await read(page,"window.__personnelClear=true");await clickText(page,"交接事项");await waitFor(page,"document.body.innerText.includes('离职前需调整部门负责人')");
  await clickText(page,"办理离职");await waitFor(page,"document.body.innerText.includes('仍担任部门负责人')");
  assert(await read(page,"[...document.querySelectorAll('.office-dialog-backdrop:last-of-type button')].find(item=>item.textContent.trim()==='办理离职').disabled"));
  await audit(page,"personnel-manager-departure-guard");
}
