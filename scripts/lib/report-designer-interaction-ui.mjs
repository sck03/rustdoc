import assert from 'node:assert/strict';
import { delay } from './chromium-cdp.mjs';

export async function verifyDesignerInteraction({ page, url, read, waitFor, click, key, modifier, results }) {
  const pointFor = selector => read(page, `(()=>{const node=document.querySelector(${JSON.stringify(selector)});node.scrollIntoView({block:'center'});node.focus({preventScroll:true});const r=node.getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+r.height/2}})()`);
  const mouse = (type, point) => page.send('Input.dispatchMouseEvent', { type, ...point, button: 'left', ...(type === 'mouseMoved' ? { buttons: 1 } : { clickCount: 1 }) });
  const pointerListeners = async () => {
    const response = await page.send('Runtime.evaluate', { expression: '(()=>{const events=getEventListeners(window);return ["pointermove","pointerup","pointercancel"].reduce((count,name)=>count+(events[name]?.length??0),0)})()', includeCommandLineAPI: true, returnByValue: true });
    assert(!response.exceptionDetails, 'DevTools must report native listener counts');
    return response.result.value;
  };
  await page.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await page.send('Page.navigate', { url: `${url}?editing=1` });
  await waitFor(page, 'document.querySelector("[data-v3-element-id=edit-other]")');
  await read(page, 'document.querySelector("[data-v3-element-id=edit-other]").focus()');
  await key(page, 'Enter');
  const x = 'window.__designerSchema.layers.flatMap(layer=>layer.elements).find(element=>element.id==="edit-other").xHundredthMm';
  const start = await read(page, x);
  await key(page, 'ArrowRight');
  await waitFor(page, `${x} === ${start + 100}`);
  await delay(550);
  await key(page, 'ArrowRight');
  await waitFor(page, `${x} === ${start + 200}`);
  await key(page, 'z', modifier);
  assert.equal(await read(page, x), start + 100, 'separate keyboard gestures keep independent undo steps in StrictMode');
  await key(page, 'z', modifier);
  assert.equal(await read(page, x), start);
  await key(page, 'y', modifier);
  assert.equal(await read(page, x), start + 100);
  await key(page, 'y', modifier);
  assert.equal(await read(page, x), start + 200);
  await key(page, 'ArrowRight');
  await key(page, 'ArrowRight');
  await waitFor(page, `${x} === ${start + 400}`);
  await click(page, 'button[aria-label="撤销"]');
  assert.equal(await read(page, x), start + 200, 'one continuous keyboard gesture undoes once');
  results.push({ test: 'StrictMode undo boundaries, grouped nudges and redo', passed: true });

  await page.send('Page.navigate', { url: `${url}?stress=1` });
  await waitFor(page, 'document.querySelector("[data-v3-element-id=stress-0]")');
  await read(page, 'document.querySelector("[data-v3-element-id=stress-0]").focus()');
  await key(page, 'Enter');
  await waitFor(page, 'document.querySelector("[data-v3-element-id=stress-0].is-selected")');
  assert.equal(await read(page, 'document.querySelectorAll(".report-designer-v3-layer-list[hidden] .report-designer-v3-layer-elements button").length'), 0, 'hidden layer lists must not mount hundreds of unused controls');
  await click(page, '.report-designer-v3-sidebar-tabs button:nth-child(3)');
  await waitFor(page, 'document.querySelectorAll(".report-designer-v3-layer-row[data-layer-role=Overlay] .report-designer-v3-layer-elements button").length===900');
  await click(page, '.report-designer-v3-layer-row[data-layer-role=Overlay] .report-designer-v3-layer-elements-disclosure summary');
  await waitFor(page, 'document.querySelectorAll(".report-designer-v3-layer-row[data-layer-role=Overlay] .report-designer-v3-layer-elements button").length===0');
  await click(page, '.report-designer-v3-sidebar-tabs button:nth-child(2)');
  await click(page, '.report-designer-v3-sidebar-tabs button:nth-child(3)');
  assert.equal(await read(page, 'document.querySelector(".report-designer-v3-layer-row[data-layer-role=Overlay] details").open'), false, 'lazy lists preserve their expansion state between resource tabs');
  results.push({ test: '900-element layer list mounts on demand and keeps disclosure state', passed: true });

  await page.send('Page.navigate', { url: `${url}?editing=1` });
  await waitFor(page, 'document.querySelector("[data-v3-element-id=edit-other]")');
  const before = await read(page, 'window.__designerHtml');
  const point = await pointFor('[data-v3-element-id=edit-other]');
  const idleListeners = await pointerListeners();
  await mouse('mousePressed', point);
  await mouse('mouseMoved', { x: point.x + 24, y: point.y });
  assert(await pointerListeners() > idleListeners, 'an active gesture owns its terminal listeners');
  await key(page, 'Escape');
  await mouse('mouseReleased', { x: point.x + 24, y: point.y });
  await delay(60);
  assert(await read(page, 'window.__designerHtml') === before, 'Escape must cancel a drag before the pointer is released');
  assert.equal(await read(page, 'document.querySelector("[data-v3-element-id=edit-other]").style.transform'), '', 'cancelled drag restores committed geometry');
  assert.equal(await read(page, 'document.querySelector("[data-v3-element-id=edit-other]").style.willChange'), '', 'cancelled drag releases compositor hints');
  assert.equal(await pointerListeners(), idleListeners, 'inactive canvases do not retain gesture listeners');
  results.push({ test: 'Escape cancels pointer movement and releases preview resources', passed: true });

  await read(page, 'document.querySelector("[data-v3-element-id=edit-text]").focus()');
  await key(page, 'Enter', modifier);
  await waitFor(page, 'document.querySelectorAll(".report-designer-v3-element.is-selected").length===2');
  const multiPoint = await pointFor('[data-v3-element-id=edit-other]');
  await mouse('mousePressed', multiPoint);
  await mouse('mouseMoved', { x: multiPoint.x + 24, y: multiPoint.y });
  assert.equal(await read(page, 'document.querySelectorAll(".report-designer-v3-element.is-selected").length'), 2, 'dragging a selected element keeps the whole selection visible');
  await mouse('mouseReleased', { x: multiPoint.x + 24, y: multiPoint.y });
  await waitFor(page, `${x} > ${start}`);
  const positions = await read(page, 'window.__designerSchema.layers.flatMap(layer=>layer.elements).filter(element=>["edit-other","edit-text"].includes(element.id)).map(element=>({id:element.id,x:element.xHundredthMm}))');
  assert.equal(positions.find(item=>item.id==='edit-other').x - 8500, positions.find(item=>item.id==='edit-text').x - 1500, 'the selected group moves by one common delta');
  await click(page, 'button[aria-label="撤销"]');
  await waitFor(page, '!window.__designerDraftState.isDirty');
  results.push({ test: 'multi-selection survives pointer movement and undoes as one group', passed: true });

  await page.send('Page.navigate', { url });
  await waitFor(page, 'document.querySelector(".report-designer-v3-band-resizer-header")');
  const height = 'window.__designerSchema.layers.find(layer=>layer.role==="Header").designHeightHundredthMm';
  const initialHeight = await read(page, height);
  await pointFor('.report-designer-v3-band-resizer-header');
  await key(page, 'ArrowDown');
  await waitFor(page, `${height} === ${initialHeight + 100}`);
  const bandPoint = await pointFor('.report-designer-v3-band-resizer-header');
  await mouse('mousePressed', bandPoint);
  await mouse('mouseMoved', { x: bandPoint.x, y: bandPoint.y + 14 });
  await key(page, 'z', modifier);
  await waitFor(page, `${height} === ${initialHeight}`);
  await mouse('mouseReleased', { x: bandPoint.x, y: bandPoint.y + 14 });
  assert.equal(await read(page, 'parseFloat(document.querySelector("[data-v3-page-canvas]").style.getPropertyValue("--v3-header-band-height"))'), initialHeight / 100, 'undo during band resizing restores current geometry instead of the stale drag origin');
  assert.equal(await read(page, height), initialHeight);
  await click(page, '.report-designer-v3-sidebar-tabs button:nth-child(3)');
  await click(page, '.report-designer-v3-layer-row[data-layer-role=Header] button[aria-label="锁定图层"]');
  await waitFor(page, 'document.querySelector(".report-designer-v3-band-resizer-header").getAttribute("aria-disabled")==="true"');
  await pointFor('.report-designer-v3-band-resizer-header');
  await key(page, 'ArrowDown');
  assert.equal(await read(page, height), initialHeight, 'locked layer height is unchanged by the keyboard');
  await click(page, '.report-designer-v3-layer-row[data-layer-role=Header] .report-designer-layer-settings summary');
  assert(await read(page, 'document.querySelector(".report-designer-v3-layer-row[data-layer-role=Header] .report-designer-v3-layer-design-fields input").disabled'), 'the numeric editor follows the same layer lock');
  results.push({ test: 'band undo cancellation and layer locks keep document and canvas aligned', passed: true });

  await page.send('Page.navigate', { url });
  await waitFor(page, 'document.querySelector("[data-v3-element-id=review-grid]")');
  await read(page, 'document.querySelector("[data-v3-element-id=review-grid]").focus()');
  await key(page, 'Enter');
  await click(page, '.report-designer-property-tabs [role=tab]:nth-child(2)');
  const widths = 'window.__designerSchema.layers.flatMap(layer=>layer.elements).find(element=>element.id==="review-grid").block.columns.map(column=>column.widthPercent)';
  const beforeWidths = await read(page, widths);
  const columnPoint = await pointFor('.new-report-column-width-handle');
  await mouse('mousePressed', columnPoint);
  await mouse('mouseMoved', { x: columnPoint.x + 24, y: columnPoint.y });
  await key(page, 'Escape');
  await mouse('mouseReleased', { x: columnPoint.x + 24, y: columnPoint.y });
  assert.deepEqual(await read(page, widths), beforeWidths, 'Escape also cancels adjacent column resizing');
  assert.equal(await pointerListeners(), idleListeners);
  results.push({ test: 'column width cancellation uses the shared pointer lifecycle', passed: true });

  const unmountPoint = await pointFor('[data-v3-element-id=review-grid]');
  await mouse('mousePressed', unmountPoint);
  await mouse('mouseMoved', { x: unmountPoint.x + 24, y: unmountPoint.y });
  await read(page, 'window.__unmountDesigner()');
  await mouse('mouseReleased', { x: unmountPoint.x + 24, y: unmountPoint.y });
  await delay(60);
  assert.equal(await pointerListeners(), idleListeners, 'leaving the workspace releases active gesture listeners');
  assert.equal(await read(page, 'window.__designerErrors.length'), 0);
  results.push({ test: 'unmount during a drag cancels work and releases native listeners', passed: true });
}
