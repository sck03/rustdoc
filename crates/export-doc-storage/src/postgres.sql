    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    identity TEXT,
    version BIGINT NOT NULL CHECK(version > 0),
    owner_id BIGINT NOT NULL,
