//! Business resources and their operations. Routes and schemas remain generated.
use crate::generated_api::*;

#[derive(Clone, Copy, Debug)]
pub struct Resource {
    pub key: &'static str,
    pub permission: &'static str,
    pub list: Operation,
    pub create: Operation,
    pub update: Operation,
    pub get: Option<Operation>,
    pub delete: Option<Operation>,
    pub identity: &'static str,
    pub schema: &'static str,
    pub result_field: &'static str,
}

macro_rules! resource {
    ($key:literal,$permission:literal,$list:ident,$create:ident,$update:ident,$get:expr,$delete:expr,$identity:literal,$schema:literal,$result:literal) => {
        Resource {
            key: $key,
            permission: $permission,
            list: $list,
            create: $create,
            update: $update,
            get: $get,
            delete: $delete,
            identity: $identity,
            schema: $schema,
            result_field: $result,
        }
    };
}

