import path from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { withOfficeUi } from './lib/native-office-ui.mjs';
import { verifySharedControlLayout } from './lib/shared-control-layout.mjs';

await withOfficeUi('shared-control-layout-ui',async({openPage,output,repo,require,invoke,url})=>{
  const bundle=path.join(output,'invoice-model.mjs');
  await require('esbuild').build({stdin:{resolveDir:path.join(repo,'apps/export-doc-web'),contents:"export {createEmptyInvoice} from './src/features/invoices/invoiceModel.ts'"},bundle:true,platform:'node',format:'esm',outfile:bundle,logLevel:'silent'});
  const {createEmptyInvoice}=await import(pathToFileURL(bundle));
  const token=(await invoke('Login',{username:'oa-review',password:'Review-2026-Test'})).accessToken;
  for(let n=0;n<21;n++) await invoke('CreateInvoice',{...createEmptyInvoice('2026-11-10'),invoiceNo:'PAGING-'+n}, {},token);
  const page=await openPage('oa-review','Review-2026-Test');
  await verifySharedControlLayout({run:expression=>page.evaluate(expression),capture:name=>page.screenshot({path:path.join(output,name+'.png')})});
  const chooser=page.waitForEvent('filechooser');
  await page.locator('[data-ui="file-input"] input').press('Enter');
  await (await chooser).setFiles({name:'中文附件.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/iZk9HQAAAABJRU5ErkJggg==','base64')});
  await page.getByRole('button',{name:'移除待保存文件 中文附件.png',exact:true}).waitFor();
  assert.equal(await page.locator('[data-ui="file-input"] input').inputValue(),'');
  const calls=[];
  page.on('request',request=>{const parsed=new URL(request.url());if(parsed.pathname==='/api/worklist')calls.push(parsed.searchParams);});
  await page.goto(url+'/#/worklist');
  await page.getByRole('navigation',{name:'分页',exact:true}).waitFor();
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  const pager=page.getByRole('navigation',{name:'分页',exact:true});
  await page.waitForFunction(()=>document.querySelector('[data-ui="pagination"]')?.textContent.includes('第 2 页'));
  await page.waitForFunction(()=>document.querySelector('[data-ui="pagination"]')?.getAttribute('aria-busy')==='false');
  assert(calls.some(query=>query.get('pageNumber')==='2'&&query.get('includeSummary')==='false'&&query.has('cursor')));
  assert.equal(await page.locator('.business-records-card').count(),1);
  await page.clock.install();
  const before=calls.length;
  await page.clock.fastForward(120001);
  assert.equal(calls.length,before,'Deep pages do not poll or recount all sources');
  await page.getByRole('button',{name:'首页',exact:true}).click();
  await page.getByLabel('每页条数',{exact:true}).selectOption('50');
  await page.waitForFunction(()=>document.querySelectorAll('.business-records-card').length===21);
  assert.match(await pager.innerText(),/第 1 页/);
  assert.equal(await page.getByRole('button',{name:'下一页',exact:true}).isDisabled(),true);
});
