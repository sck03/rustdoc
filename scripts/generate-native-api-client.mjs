import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

// This is a consumer operation selection, never a second route/schema catalog.
// All routes, request/response types and their transitive properties come from
// the unmodified C# host's official /openapi/v1.json.
// The complete contract is used by the native application and the parity audit.
// A missing native implementation is reported explicitly, never routed to a
// guessed endpoint or silently replaced with a sample response.
const args = process.argv.slice(2);
const sourceIndex = args.indexOf("--openapi");
if (sourceIndex < 0 || !args[sourceIndex + 1]) {
  throw new Error("Usage: node scripts/generate-native-api-client.mjs --openapi <official-openapi.json> [--check]");
}
const document = JSON.parse(readFileSync(args[sourceIndex + 1], "utf8").replace(/^\uFEFF/u, ""));
if (!document.openapi?.startsWith("3.")) throw new Error("Expected the official OpenAPI 3 document.");
if (!document["x-exportdoc-permissions"]?.resources?.length) throw new Error("The official OpenAPI must include its generated permission catalog.");
if (!document["x-exportdoc-configuration"]?.defaults?.system?.appName) throw new Error("The official OpenAPI must include the reference configuration defaults.");
const schemas = document.components?.schemas ?? {};
const operations = [];
for (const [path, item] of Object.entries(document.paths ?? {})) {
  for (const [method, operation] of Object.entries(item)) {
    if (["get", "post", "put", "patch", "delete"].includes(method) && operation.operationId) operations.push({ path, method, ...operation });
  }
}
operations.sort((a, b) => a.operationId.localeCompare(b.operationId, "en"));
for (const operation of operations) {
  if (operations.filter((op) => op.operationId === operation.operationId).length !== 1) throw new Error(`Duplicate operation: ${operation.operationId}`);
}
const requiredSchemas = new Set();
function collect(value) {
  if (!value || typeof value !== "object") return;
  if (value.$ref) {
    const name = value.$ref.replace(/^#\/components\/schemas\//u, "");
    if (!schemas[name]) throw new Error(`Unresolved schema ${value.$ref}`);
    if (!requiredSchemas.has(name)) { requiredSchemas.add(name); collect(schemas[name]); }
  }
  for (const entry of Object.values(value)) collect(entry);
}
operations.forEach(collect);
const snake = (value) => value.replace(/([A-Z]+)([A-Z][a-z])/gu, "$1_$2").replace(/([a-z0-9])([A-Z])/gu, "$1_$2").toLowerCase();
const safe = (value) => ["type", "ref", "self", "match", "loop", "move", "default", "use", "in"].includes(snake(value)) ? `r#${snake(value)}` : snake(value);
const typesOf = (schema) => Array.isArray(schema.type) ? schema.type : [schema.type];
function nullable(schema) {
  return typesOf(schema).includes("null") || schema.nullable === true || (schema.anyOf ?? []).some((s) => s.type === "null");
}
function rustType(schema, optional = false) {
  if (!schema) return "serde_json::Value";
  const alternatives = (schema.anyOf ?? schema.oneOf ?? []).filter((s) => s.type !== "null");
  let result;
  if (schema.$ref) result = schema.$ref.split("/").at(-1);
  else if (schema.enum?.every((value) => typeof value === "string")) result = "String";
  else if (alternatives.length === 1) result = rustType(alternatives[0]);
  else if (typesOf(schema).includes("integer")) result = "i64";
  else if (typesOf(schema).includes("number")) result = "rust_decimal::Decimal";
  else if (typesOf(schema).includes("string")) result = "String";
  else if (typesOf(schema).includes("boolean")) result = "bool";
  else if (schema.type === "array") result = `Vec<${rustType(schema.items)}>`;
  else if (schema.type === "object" && schema.additionalProperties && typeof schema.additionalProperties === "object") result = `std::collections::BTreeMap<String, ${rustType(schema.additionalProperties)}>`;
  else result = "serde_json::Value";
  return optional || nullable(schema) ? `Option<${result}>` : result;
}
const names = [...requiredSchemas].sort();
const input = { operations, schemas: Object.fromEntries(names.map((name) => [name, schemas[name]])), permissions: document["x-exportdoc-permissions"], configuration: document["x-exportdoc-configuration"] };
const digest = createHash("sha256").update(JSON.stringify(input)).digest("hex");
let output = `// @generated by scripts/generate-native-api-client.mjs from official /openapi/v1.json\n// Do not edit. Selected contract SHA-256: ${digest}\n#![allow(dead_code)]\nuse serde::{Deserialize, Serialize};\n\n`;
output += '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct Operation { pub id: &\'static str, pub method: &\'static str, pub path: &\'static str, pub requires_authentication: bool }\n\n';
for (const operation of operations) {
  const name = operation.operationId[0].toUpperCase() + operation.operationId.slice(1);
  if (!operation["x-exportdoc-policy"]) throw new Error(`Missing policy metadata: ${operation.operationId}`);
  output += `pub const ${snake(operation.operationId).toUpperCase()}: Operation = Operation { id: ${JSON.stringify(operation.operationId)}, method: ${JSON.stringify(operation.method.toUpperCase())}, path: ${JSON.stringify(operation.path)}, requires_authentication: ${operation["x-exportdoc-policy"].requiresAuthentication} };\n`;
  const body = operation.requestBody?.content?.["application/json"]?.schema;
  if (body) output += `pub type ${name}Body = ${rustType(body)};\n`;
  const success = Object.entries(operation.responses ?? {}).find(([code]) => /^2\d\d$/u.test(code));
  const response = success?.[1]?.content?.["application/json"]?.schema;
  if (response) output += `pub type ${name}Response = ${rustType(response)};\n`;
}
output += "\n";
output += `pub const ALL_OPERATIONS: &[Operation] = &[${operations.map(op => snake(op.operationId).toUpperCase()).join(",")}];\n\n`;
for (const name of names) {
  const schema = schemas[name];
  if (!schema.properties) { output += `pub type ${name} = ${rustType(schema)};\n\n`; continue; }
  output += "#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]\n";
  output += `pub struct ${name} {\n`;
  for (const [key, value] of Object.entries(schema.properties)) {
    const optional = !(schema.required ?? []).includes(key);
    output += `    #[serde(rename = ${JSON.stringify(key)}${optional || nullable(value) ? ', default, skip_serializing_if = "Option::is_none"' : ""})]\n`;
    output += `    pub ${safe(key)}: ${rustType(value, optional)},\n`;
  }
  // Keep future server-side fields when editing an invoice using a narrower UI.
  // Required known response properties remain required during deserialization.
  output += '    #[serde(flatten)]\n    pub extra: std::collections::BTreeMap<String, serde_json::Value>,\n}\n\n';
}
const destination = fileURLToPath(new URL("../crates/export-doc-contracts/src/generated_api.rs", import.meta.url));
const format = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], { input: output, encoding: "utf8", timeout: 60_000, maxBuffer: 16 * 1024 * 1024 });
if (format.status !== 0) throw new Error(`rustfmt failed: ${format.stderr}`);
output = format.stdout.replace(/\r\n/gu, "\n");
const contractPath = fileURLToPath(new URL("../crates/export-doc-contracts/src/generated_contract.json", import.meta.url));
const contract = `${JSON.stringify({ source: "official /openapi/v1.json", digest, configuration: input.configuration, permissions: input.permissions, operations: Object.fromEntries(operations.map(op => [op.operationId, { policy: op["x-exportdoc-policy"], parameters: op.parameters ?? [], requestBody: op.requestBody ?? null, responses: op.responses, request: op.requestBody?.content?.["application/json"]?.schema ?? null, response: Object.entries(op.responses ?? {}).find(([code]) => /^2\d\d$/u.test(code))?.[1]?.content?.["application/json"]?.schema ?? null }])), schemas: input.schemas }, null, 2)}\n`;
const openapiPath = fileURLToPath(new URL("../crates/export-doc-contracts/src/openapi.json", import.meta.url));
const openapi = JSON.stringify(document, null, 2) + "\n";
if (args.includes("--check")) {
  if (readFileSync(destination, "utf8").replace(/\r\n/gu, "\n") !== output || readFileSync(contractPath, "utf8").replace(/\r\n/gu, "\n") !== contract || readFileSync(openapiPath, "utf8").replace(/\r\n/gu, "\n") !== openapi) throw new Error("Native API contract drift. Regenerate from the current official OpenAPI.");
} else {
  writeFileSync(destination, output, "utf8");
  writeFileSync(contractPath, contract, "utf8");
  writeFileSync(openapiPath, openapi, "utf8");
}
console.log(`Native OpenAPI client: ${operations.length} operations, ${names.length} schemas; ${args.includes("--check") ? "verified" : "generated"}.`);
