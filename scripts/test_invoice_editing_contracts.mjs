import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, ".."), web = path.join(root, "apps/export-doc-web");
const require = createRequire(path.join(web, "package.json"));
const output = path.join(root, ".codex-runtime/invoice-editing-models");
fs.mkdirSync(output, { recursive: true });
const bundle = path.join(output, "models.mjs");
const source = name => JSON.stringify(path.join(web, "src", name).replaceAll("\\", "/"));
await require("esbuild").build({ stdin: { resolveDir: web, loader: "ts", contents: `
export * as items from ${source("features/invoices/invoiceItemsEditorModel.ts")};
export * as table from ${source("features/invoices/invoiceItemTableModel.ts")};
export * as invoice from ${source("features/invoices/invoiceModel.ts")};
export * as save from ${source("features/invoices/invoiceSaveModel.ts")};
export * as grid from ${source("features/report-designer/reportDesignerGridTextImport.ts")};
export * as decimal from ${source("ui/decimalSum.ts")};` }, outfile: bundle, bundle: true, platform: "node", format: "esm", logLevel: "silent" });
const { items, table, invoice, save, grid, decimal } = await import(pathToFileURL(bundle).href);
const cases = JSON.parse(fs.readFileSync(path.join(root, "tests/ContractFixtures/invoice-arithmetic.json"), "utf8"));
for (const test of cases) {
  const input = { ...items.createEmptyInvoiceItem(), quantity: Number(test.quantity), unitPrice: Number(test.unitPrice) };
  const result = items.recalculateInvoiceItem(input, ["quantity", "unitPrice"]);
  assert.equal(result.totalPrice, Number(test.expectedAmount), JSON.stringify(test));
  assert.equal(result.unitPrice, Number(test.expectedUnitPrice));
  assert.equal(items.normalizeInvoiceItemForSave(input).totalPrice, result.totalPrice);
}
assert.equal(items.roundMoney(-1.005), -1.01);
assert.equal(decimal.sumDecimalNumbers([0.1, 0.2]), 0.3);
assert.equal(decimal.ExactDecimal.from("12345678901234567890.12345678").round(2).toString(), "12345678901234567890.12");
const cartons = items.recalculateInvoiceItem({ ...items.createEmptyInvoiceItem(), quantity: 0.14, pcsPerCtn: 0.01 }, ["quantity"]);
assert.equal(cartons.cartons, 14);
assert.equal(items.recalculateInvoiceItem({ ...items.createEmptyInvoiceItem(), quantity:1, purchasePrice:1.005 }, ["purchasePrice"]).purchaseTotal, 1.01);
const totals = items.calculateInvoiceTotals([{ ...items.createEmptyInvoiceItem(), totalPrice:0.1 }, { ...items.createEmptyInvoiceItem(), totalPrice:0.2 }], 1, "CNY");
assert.equal(totals.totalAmount, 0.3);
const mutable = { ...items.createEmptyInvoiceItem(), quantity:1, unitPrice:1.005, totalPrice:1.01 };
const firstCopy = items.normalizeInvoiceItemForSave(mutable); firstCopy.totalPrice = 999;
assert.equal(items.normalizeInvoiceItemForSave(mutable).totalPrice, 1.01, "returned DTO mutation must not contaminate normalization cache");
mutable.unitPrice = 2.675; mutable.totalPrice = 2.68;
assert.equal(items.normalizeInvoiceItemForSave(mutable).totalPrice, 2.68, "input mutations invalidate normalized rows");
assert.equal(items.calculateInvoiceTotals([mutable],1,"CNY").totalAmount,2.68);
mutable.totalPrice=3.01;
assert.equal(items.calculateInvoiceTotals([mutable],1,"CNY").totalAmount,3.01,"input mutations invalidate exact row totals");
const quoted = '"Line 1\nLine 2"\t"a\tand\t\"\"b\"\""\t\r\n';
const expected = [["Line 1\nLine 2", 'a\tand\t"b"', ""]];
assert.deepEqual(items.parseInvoiceItemClipboardRows(quoted), expected);
assert.deepEqual(grid.parseGridText(quoted), expected);
assert.throws(() => items.parseInvoiceItemClipboardRows('"unfinished'), /引号/);
assert.throws(() => items.parseInvoiceItemClipboardRows(Array(5001).fill("item").join("\n")), /5000/);
assert.throws(() => grid.parseGridText("a\tb\nc"), /列数/);
const selectedColumns = table.invoiceItemEditableColumns;
const manyRows = Array.from({ length: 5000 }, (_, index) => ({ ...items.createEmptyInvoiceItem(), styleNo: `ROW-${index}` }));
const manyCells = manyRows.flatMap((_, rowIndex) => selectedColumns.map(column => ({ rowIndex, field: column.field })));
assert.equal(manyCells.length, 5000 * 38);
assert.equal(items.getInvoiceItemSelectionBounds(manyCells, selectedColumns).rowEnd, 4999);
assert.equal(items.buildSelectedCellsClipboardText(manyCells, manyRows, selectedColumns).split("\n").length, 5000);
const shortened = items.calculateInvoiceItemVirtualRange(300, 200000, 600, true);
assert.ok(shortened.startIndex < shortened.endIndex && shortened.endIndex <= 300);
assert.ok(shortened.topSpacerHeight < 300 * 42);
assert.equal(items.haveInvoiceTotalsInputsChanged(manyRows, manyRows.map((row, i) => i ? row : { ...row, styleName: "edited text" })), false);
assert.equal(items.haveInvoiceTotalsInputsChanged(manyRows, manyRows.map((row, i) => i ? row : { ...row, totalPrice: 1 })), true);
const before = { ...invoice.createEmptyInvoice("2026-10-25"), id:7, invoiceNo:"submitted", rowVersion:"native:1" };
const saved = { ...before, rowVersion:"native:2" };
const current = { ...before, invoiceNo:"new unsaved" };
const kept = save.reconcileSavedInvoice(current, invoice.normalizeInvoiceForSave(before, 7), saved);
assert.equal(kept.changed, true); assert.equal(kept.invoice.invoiceNo, "new unsaved"); assert.equal(kept.invoice.rowVersion, "native:2");
assert.equal(save.reconcileSavedInvoice(before, invoice.normalizeInvoiceForSave(before, 7), saved).changed, false);
assert.equal(save.readInvoiceSaveContinuation({ invoiceSaveContinuation:{invoice:kept.invoice,feedback:[]} }, saved).invoice.invoiceNo, "new unsaved");
assert.equal(save.readInvoiceSaveContinuation({ invoiceSaveContinuation:{invoice:kept.invoice,feedback:[]} }, { ...saved, rowVersion:"native:3" }), null);
assert.deepEqual(save.remainingHsFeedback([{ queryText:"saved" }, { queryText:"new" }], [{ queryText:"saved" }]), [{ queryText:"new" }]);
console.log(`Invoice editing contracts passed; ${cases.length} shared Rust/React arithmetic cases, exact totals, TSV and save reconciliation.`);
