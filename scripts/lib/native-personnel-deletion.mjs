import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { captureScreenshot } from './web-runtime-browser-session.mjs';
import { waitFor } from './web-runtime-smoke-common.mjs';

export async function verifyDesktopPersonnelDeletion({ run, request, token, cdp, output }) {
  const web = path.resolve(import.meta.dirname, '../../apps/export-doc-web');
  const bundle = path.join(output, 'personnel-delete-model.mjs');
  await createRequire(path.join(web, 'package.json'))('esbuild').build({ stdin: { resolveDir: web, contents: "export {readPersonnelCreate} from './src/features/office/personnelModel.ts';" }, bundle: true, platform: 'node', format: 'esm', outfile: bundle, logLevel: 'silent' });
  const { readPersonnelCreate } = await import(pathToFileURL(bundle).href);
  const wait = expression => waitFor(() => run(`Boolean(${expression})`), 30000, expression);
  const create = async key => {
    const form = new FormData();
    for (const [field, value] of Object.entries({ employeeNumber: key, fullName: '删除保护验收', departmentId: 'GENERAL', jobTitle: '测试', employmentType: 'FullTime', hireDate: '2026-10-19' })) form.set(field, value);
    const result = await request('CreatePersonnel', token, readPersonnelCreate(form, key));
    assert.equal(result.status, 200, JSON.stringify(result.body));
    return result.body;
  };
  const button = "[...document.querySelectorAll('button')].find(e=>e.textContent.trim()==='删除误录档案')";
  const unlinked = await create('DELETE-UNLINKED');
  await run(`location.hash='#/office/people/${unlinked.employee.id}'; true`);
  await wait(button);
  assert.equal(await run(`${button}.disabled`), false, 'Administrator may correct an unreferenced entry');
  const edit = "[...document.querySelectorAll('button')].find(e=>e.textContent==='编辑档案')";
  const close = "document.querySelector('[role=dialog] button[aria-label=关闭窗口]')";
  const correction = "document.querySelector('[role=dialog] [data-dialog-control] input')";
  const confirmation = "document.querySelector('.confirmation-dialog')";
  async function click(expression) {
    await wait(expression);
    const point = await run(`(() => { const r = (${expression}).getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; })()`);
    await cdp.send('Input.dispatchMouseEvent', { type: 'mousePressed', button: 'left', clickCount: 1, ...point });
    await cdp.send('Input.dispatchMouseEvent', { type: 'mouseReleased', button: 'left', clickCount: 1, ...point });
  }
  await click(edit);
  await click(correction);
  await click(close);
  await wait("!document.querySelector('[role=dialog]')");
  await click(edit);
  await click(correction);
  await run("document.querySelector('input[name=fullName]').focus(); true");
  await cdp.send('Input.insertText', { text: '未保存的修改' });
  await click(close);
  await wait(confirmation);
  await captureScreenshot(cdp, path.join(output, 'Full-personnel-discard.png'));
  await click("[...document.querySelectorAll('.confirmation-dialog button')].find(e=>e.textContent.trim()==='取消')");
  await wait(`!${confirmation}`);
  assert(await run(`Boolean(${close})`), 'Cancel keeps the personnel draft open');
  await click(close);
  await click("[...document.querySelectorAll('.confirmation-dialog button')].find(e=>e.textContent.trim()==='放弃并关闭')");
  await wait("!document.querySelector('[role=dialog]')");
  assert.equal((await request('GetPersonnel', token, undefined, { id: unlinked.employee.id })).body.versionNumber, unlinked.versionNumber, 'Discard does not save personnel changes');
  await run(`${button}.click(); true`);
  await wait("document.querySelector('textarea[name=reason]')");
  await run("document.querySelector('textarea[name=reason]').focus(); true");
  await cdp.send('Input.insertText', { text: '隔离验收误录纠正' });
  await run("document.querySelector('[role=dialog] input[type=checkbox]').click(); [...document.querySelectorAll('[role=dialog] button')].find(e=>e.textContent==='确认删除').click(); true");
  await waitFor(async () => (await request('GetPersonnel', token, undefined, { id: unlinked.employee.id })).status === 404, 30000, 'Unreferenced employee was not deleted');
  const linked = await create('DELETE-LINKED');
  const account = await request('createUserAccount', token, { username: 'delete-protection', fullName: '关联账号验收', role: 'OfficeEmployee', permissionTemplateId: null, companyScope: 'DEFAULT', departmentId: 'GENERAL', isActive: true, resetPassword: 'Delete-Protection-2026' });
  assert.equal(account.status, 200, JSON.stringify(account.body));
  const result = await request('LinkPersonnelAccount', token, { expectedVersion: linked.versionNumber, userId: account.body.user.id, expectedAccountVersion: account.body.user.versionNumber }, { id: linked.employee.id });
  assert.equal(result.status, 200, JSON.stringify(result.body));
  assert.equal(result.body.canDelete, true);
  assert(result.body.deleteRestriction.includes('关联登录账号'));
  await run(`location.hash='#/office/people/${linked.employee.id}'; true`);
  await wait("document.querySelector('#personnel-delete-restriction')");
  assert.equal(await run(`${button}.disabled`), true);
  assert((await run("document.querySelector('#personnel-delete-restriction').textContent")).includes('当前账号有删除权限'));
  const denied = await request('DeletePersonnel', token, { expectedVersion: result.body.versionNumber, reason: '测试拒绝绕过' }, { id: linked.employee.id });
  assert.equal(denied.status, 409, JSON.stringify(denied.body));
  await captureScreenshot(cdp, path.join(output, 'Full-personnel-delete-reason.png'));
  await run("[...document.querySelectorAll('button')].find(e=>e.textContent==='关联账号').click(); true");
  await wait("document.querySelector('[role=dialog]')?.textContent.includes('delete-protection')");
  assert.equal(await run("document.querySelector('[role=dialog] input[type=radio], [aria-label=搜索可关联账号]')!==null"), false, 'A linked person displays the current account without loading a replacement picker');
  await captureScreenshot(cdp, path.join(output, 'Full-personnel-current-account.png'));
  await run("[...document.querySelectorAll('[role=dialog] button')].find(e=>e.textContent==='解除账号绑定').click(); true");
  await wait("document.querySelector('[role=dialog] textarea[name=reason]')");
  await run("document.querySelector('[role=dialog] textarea[name=reason]').focus(); true");
  await cdp.send('Input.insertText', { text: '纠正隔离验收账号关联' });
  await run("[...document.querySelectorAll('[role=dialog] button')].find(e=>e.textContent==='确认解除绑定').click(); true");
  await waitFor(async () => (await request('GetPersonnel', token, undefined, { id: linked.employee.id })).body.account === null, 30000, 'Personnel account was not unlinked');
  await wait("!document.querySelector('[role=dialog]')");
  const users = (await request('ListUsers', token)).body.users;
  const preserved = users.find(user => user.id === account.body.user.id);
  assert.equal(preserved.isActive, true);
  assert.equal(preserved.employee, null);
  assert.equal(await run(`${button}.disabled`), true, 'Unlinking must preserve historical deletion protection');
  assert.equal(await run("[...document.querySelectorAll('button')].some(e=>e.textContent==='解除账号绑定')"), false);
  const replacement = await request('createUserAccount', token, { username: 'replacement-account', fullName: '重新关联验收', role: 'OfficeEmployee', companyScope: 'DEFAULT', departmentId: 'GENERAL', isActive: true, resetPassword: 'Replacement-2026' });
  assert.equal(replacement.status, 200);
  await run("[...document.querySelectorAll('button')].find(e=>e.textContent==='关联账号').click(); true");
  const replacementRadio = `document.querySelector('[role=dialog] input[type=radio][value="${replacement.body.user.id}"]')`;
  await wait(replacementRadio);
  await run(`${replacementRadio}.click(); true`);
  await run("[...document.querySelectorAll('[role=dialog] button')].find(e=>e.textContent==='确认关联').click(); true");
  await waitFor(async () => (await request('GetPersonnel', token, undefined, { id: linked.employee.id })).body.account?.id === replacement.body.user.id, 30000, 'A different account can be linked only after unlinking');
  await wait("!document.querySelector('[role=dialog]')");
  await run("[...document.querySelectorAll('button')].find(e=>e.textContent==='任职与操作记录').click(); true");
  await wait("document.querySelector('.office-history')?.textContent.includes('解除账号绑定')");
  await captureScreenshot(cdp, path.join(output, 'Full-personnel-unlinked.png'));
}
